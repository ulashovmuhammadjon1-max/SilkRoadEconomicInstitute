#!/usr/bin/env node
/**
 * Builds components/map/paths.ts from Natural Earth 1:50m Admin-0 countries.
 *
 * Source: Natural Earth (https://www.naturalearthdata.com), public domain.
 * Download ne_50m_admin_0_countries.geojson from
 * https://github.com/nvkelso/natural-earth-vector/tree/master/geojson
 *
 * Usage: node scripts/build-map.mjs path/to/ne_50m_admin_0_countries.geojson
 *
 * Projection: equirectangular, x scaled by cos(45°), cropped to lon 0–135, lat 15–72.
 * Simplification: Douglas–Peucker (0.7 units for Central Asia, 2.4 for context), tiny islands dropped.
 */
import fs from "node:fs";
import path from "node:path";

const src = process.argv[2];
if (!src) {
  console.error("Usage: node scripts/build-map.mjs <ne_50m_admin_0_countries.geojson>");
  process.exit(1);
}

const LON0 = 0, LON1 = 135, LAT0 = 15, LAT1 = 72;
const KX = Math.cos((45 * Math.PI) / 180);
export const W = 1000;
const K = W / ((LON1 - LON0) * KX);
export const H = Math.round((LAT1 - LAT0) * K);
const FOCUS = new Set(["UZB", "KAZ", "KGZ", "TJK", "TKM"]);

const project = ([lon, lat]) => [(lon - LON0) * KX * K, (LAT1 - lat) * K];

function dp(points, tol) {
  if (points.length < 3) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = points[a], [bx, by] = points[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1;
    let max = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * points[i][0] - dx * points[i][1] + bx * ay - by * ax) / len;
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol && idx > 0) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return points.filter((_, i) => keep[i]);
}

const area = (r) => Math.abs(r.reduce((s, [x, y], i) => { const [x2, y2] = r[(i + 1) % r.length]; return s + x * y2 - x2 * y; }, 0) / 2);
const inView = (r) => r.some(([x, y]) => x > -40 && x < W + 40 && y > -40 && y < H + 40);
const fmt = (n) => Math.round(n).toString();

function ringsToPath(rings, tol, minArea) {
  let d = "";
  for (const ring of rings) {
    // Split the closed ring in two halves so Douglas–Peucker has distinct endpoints.
    const open = ring.slice(0, -1).map(project);
    const mid = Math.floor(open.length / 2);
    const pts = [...dp(open.slice(0, mid + 1), tol).slice(0, -1), ...dp(open.slice(mid).concat([open[0]]), tol).slice(0, -1)];
    if (pts.length < 3 || area(pts) < minArea || !inView(pts)) continue;
    d += "M" + pts.map(([x, y]) => `${fmt(x)} ${fmt(y)}`).join("L") + "Z";
  }
  return d;
}

const geo = JSON.parse(fs.readFileSync(src, "utf8"));
const focus = [], context = [];
for (const f of geo.features) {
  const code = f.properties.ADM0_A3 || f.properties.ISO_A3;
  const g = f.geometry;
  if (!g) continue;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : [];
  // outer rings only; holes are irrelevant at this scale
  const isFocus = FOCUS.has(code);
  const d = isFocus ? ringsToPath(polys.map((p) => p[0]), 0.7, 4) : ringsToPath(polys.map((p) => p[0]), 2.4, 40);
  if (!d) continue;
  (isFocus ? focus : context).push({ code, name: f.properties.NAME, d });
}

const city = (name, lon, lat) => { const [x, y] = project([lon, lat]); return { name, x: +fmt(x), y: +fmt(y) }; };
const origins = [
  city("Tashkent", 69.24, 41.31),
  city("Samarkand", 66.96, 39.65),
  city("Bishkek", 74.59, 42.87),
  city("Dushanbe", 68.79, 38.56),
  city("Almaty", 76.89, 43.24),
  city("Ashgabat", 58.38, 37.95),
];
const destinations = [
  { key: "russia", label: "Russia", ...city("Moscow", 37.62, 55.75) },
  { key: "korea", label: "South Korea", ...city("Seoul", 126.98, 37.57) },
  { key: "gulf", label: "The Gulf", ...city("Dubai", 55.27, 25.2) },
  { key: "europe", label: "Europe", ...city("Berlin", 13.4, 52.52) },
];

const out = `/* eslint-disable */
// GENERATED by scripts/build-map.mjs. Do not edit by hand.
// Geography: Natural Earth 1:50m Admin-0 countries (public domain), simplified.
// Decorative illustration only: not to scale, not data.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const focusCountries = ${JSON.stringify(focus)} as const;
export const contextCountries = ${JSON.stringify(context.map(({ code, d }) => ({ code, d })))} as const;
export const origins = ${JSON.stringify(origins)} as const;
export const destinations = ${JSON.stringify(destinations)} as const;
`;
const target = path.join(process.cwd(), "components/map/paths.ts");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`wrote ${target}: ${(out.length / 1024).toFixed(1)} KB, ${focus.length} focus + ${context.length} context countries, viewBox ${W}x${H}`);
